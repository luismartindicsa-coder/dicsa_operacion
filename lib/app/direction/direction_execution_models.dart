/// Confirmed totals retain the original baseline and synchronize the agenda.
/// Shipments are reconciled by day/client/material; production by day/shift/material.
class DirectionExecutionActual {
  final String kind, material, client, shift, notes;
  final DateTime date;
  final int quantity, revision;
  final int? observedQuantity, plannedQuantity;
  final List<int> loads;
  final bool active;
  final String? programId;
  final int agendaSyncedRevision;
  final List<DirectionExecutionAgendaChange> agendaChanges;
  const DirectionExecutionActual({
    required this.kind,
    required this.date,
    required this.material,
    required this.quantity,
    this.client = '',
    this.shift = '',
    this.notes = '',
    this.revision = 0,
    this.observedQuantity,
    this.plannedQuantity,
    this.loads = const [],
    this.active = true,
    this.programId,
    this.agendaSyncedRevision = 0,
    this.agendaChanges = const [],
  });
  String get key => directionExecutionKey(kind, date, material, client, shift);
  bool get agendaSynced =>
      kind == 'shipment' && revision > 0 && agendaSyncedRevision == revision;
  factory DirectionExecutionActual.fromRow(Map<String, dynamic> row) =>
      DirectionExecutionActual(
        kind: row['kind'] as String,
        date: _parseDate(row['op_date']),
        material: row['material_code'] as String,
        client: row['client_name'] as String? ?? '',
        shift: row['shift'] as String? ?? '',
        notes: row['notes'] as String? ?? '',
        quantity: (row['quantity'] as num).toInt(),
        revision: (row['revision'] as num).toInt(),
        observedQuantity: (row['observed_quantity'] as num?)?.toInt(),
        plannedQuantity: (row['planned_quantity'] as num?)?.toInt(),
        loads: (row['load_quantities'] as List? ?? [])
            .map((n) => (n as num).toInt())
            .toList(),
        active: row['active'] as bool? ?? true,
        programId: row['program_id'] as String?,
        agendaSyncedRevision:
            (row['agenda_synced_revision'] as num?)?.toInt() ?? 0,
        agendaChanges: (row['agenda_snapshot'] as List? ?? [])
            .map(
              (v) => DirectionExecutionAgendaChange.fromRow(
                Map<String, dynamic>.from(v as Map),
              ),
            )
            .toList(),
      );
}

class DirectionExecutionAgendaChange {
  final DirectionShipmentPlanRecord? before;
  final DirectionShipmentPlanRecord after;
  const DirectionExecutionAgendaChange({this.before, required this.after});
  factory DirectionExecutionAgendaChange.fromRow(Map<String, dynamic> row) =>
      DirectionExecutionAgendaChange(
        before: row['before'] == null
            ? null
            : DirectionShipmentPlanRecord.fromRow(
                Map<String, dynamic>.from(row['before'] as Map),
              ),
        after: DirectionShipmentPlanRecord.fromRow(
          Map<String, dynamic>.from(row['after'] as Map),
        ),
      );
  bool matches(DirectionShipmentPlanRecord p) =>
      p.id == after.id &&
      p.shipDate == after.shipDate &&
      directionExecutionClient(p.clientName) ==
          directionExecutionClient(after.clientName) &&
      p.materialCode == after.materialCode &&
      p.plannedQuantity == after.plannedQuantity &&
      p.status == after.status;
}

/// Agenda rows generated by a confirmation are not independent observations.
/// Replay their original source (if any) so confirmation does not feed itself
/// back into Operation prefill, floor inventory or the historical reconciliation.
List<DirectionShipmentPlanRecord> directionShipmentSourcePlans(
  List<DirectionShipmentPlanRecord> plans,
  List<DirectionExecutionActual> actuals,
) {
  final changes = {
    for (final a in actuals.where((a) => a.kind == 'shipment'))
      for (final change in a.agendaChanges) change.after.id: change,
  };
  return [
    for (final p in plans)
      if (changes[p.id]?.matches(p) != true)
        p
      else if (changes[p.id]!.before != null)
        changes[p.id]!.before!,
  ];
}

String directionExecutionClient(String client) => _suggestionClient(client);
List<DirectionShipmentPlanRecord> directionOutstandingShipmentPlans(
  List<DirectionShipmentPlanRecord> plans,
  List<DirectionExecutionActual> actuals,
  DateTime today,
) {
  final credits = {
    for (final a in actuals)
      if (a.active && a.kind == 'shipment' && !a.date.isAfter(today))
        a.key: a.quantity,
  };
  // The daily confirmation includes rows already marked shipped as well.
  for (final p in plans.where((p) => p.isShipped)) {
    final key = directionExecutionKey(
      'shipment',
      p.shipDate,
      p.materialCode,
      p.clientName,
    );
    credits[key] = math.max(0, (credits[key] ?? 0) - p.plannedQuantity);
  }
  final result = <DirectionShipmentPlanRecord>[];
  for (final p in [...plans]..sort((a, b) => a.id.compareTo(b.id))) {
    if (!p.isActive) {
      result.add(p);
      continue;
    }
    final key = directionExecutionKey(
      'shipment',
      p.shipDate,
      p.materialCode,
      p.clientName,
    );
    final covered = math.min(p.plannedQuantity, credits[key] ?? 0);
    credits[key] = (credits[key] ?? 0) - covered;
    if (covered == 0) {
      result.add(p);
      continue;
    }
    if (covered == p.plannedQuantity) continue;
    result.add(
      DirectionShipmentPlanRecord(
        id: p.id,
        shipDate: p.shipDate,
        clientName: p.clientName,
        materialCode: p.materialCode,
        materialScope: p.materialScope,
        quantityUnit: p.quantityUnit,
        plannedQuantity: p.plannedQuantity - covered,
        priority: p.priority,
        status: p.status,
        notes: p.notes,
        createdAt: p.createdAt,
        updatedAt: p.updatedAt,
      ),
    );
  }
  return result;
}

String directionExecutionKey(
  String kind,
  DateTime date,
  String material, [
  String client = '',
  String shift = '',
]) => jsonEncode([
  kind,
  _fmtDate(date),
  material,
  kind == 'shipment' ? directionExecutionClient(client) : '',
  kind == 'production' ? shift : '',
]);

class DirectionExecutionRow {
  final String kind, material, client, shift;
  final DateTime date;
  final int? planned, observed;
  final List<int> observedLoads;
  final DirectionExecutionActual? confirmation;
  const DirectionExecutionRow({
    required this.kind,
    required this.date,
    required this.material,
    this.client = '',
    this.shift = '',
    this.planned,
    this.observed,
    this.observedLoads = const [],
    this.confirmation,
  });
  String get key => directionExecutionKey(kind, date, material, client, shift);
  bool get confirmed => confirmation?.active == true;
  int? get actual => confirmed ? confirmation!.quantity : observed;
  int? get baseline => confirmed ? confirmation!.plannedQuantity : planned;
  int? get difference =>
      actual == null || baseline == null ? null : actual! - baseline!;
  bool get sourceChanged =>
      confirmed && observed != confirmation!.observedQuantity;
}

/// Confirmed totals replace the same source cell; zero is an observed zero,
/// never a missing reading and never an extra production run.
List<DirectionProductionHistoryRecord> directionProductionWithActuals(
  List<DirectionProductionHistoryRecord> records,
  List<DirectionExecutionActual> actuals, {
  required DateTime before,
}) {
  final confirmed = {
    for (final a in actuals)
      if (a.active && a.kind == 'production' && a.date.isBefore(before))
        a.key: a,
  };
  final sourceTotals = <String, int>{};
  for (final r in records) {
    final key = directionExecutionKey(
      'production',
      r.date,
      r.materialCode,
      '',
      r.shiftKey,
    );
    sourceTotals[key] = (sourceTotals[key] ?? 0) + r.quantity;
  }
  // Preserve physical timestamps and machine attribution for unchanged totals.
  confirmed.removeWhere(
    (key, a) => a.quantity > 0 && sourceTotals[key] == a.quantity,
  );
  return [
    for (final r in records)
      if (!confirmed.containsKey(
        directionExecutionKey(
          'production',
          r.date,
          r.materialCode,
          '',
          r.shiftKey,
        ),
      ))
        r,
    for (final a in confirmed.values)
      DirectionProductionHistoryRecord(
        date: a.date,
        materialCode: a.material,
        quantity: a.quantity,
        shiftKey: a.shift,
        source: 'direction_execution_actuals',
      ),
  ];
}

List<DirectionExecutionRow> buildDirectionExecutionRows({
  required String kind,
  required DateTime week,
  required List<DirectionShipmentPlanRecord> shipments,
  required List<DirectionShipmentMovement> movements,
  required List<DirectionProductionHistoryRecord> production,
  required List<DirectionExecutionActual> confirmations,
  Map<String, int> plannedProduction = const {},
}) {
  final rows = <String, DirectionExecutionRow>{};
  final planned = <String, int>{},
      operations = <String, int>{},
      legacy = <String, int>{};
  final operationLoads = <String, List<int>>{},
      legacyLoads = <String, List<int>>{};
  final saved = {
    for (final a in confirmations.where((a) => a.kind == kind)) a.key: a,
  };
  void seed(
    DateTime date,
    String material, [
    String client = '',
    String shift = '',
  ]) {
    if (date.isBefore(week) ||
        !date.isBefore(week.add(Duration(days: kind == 'production' ? 5 : 6))))
      return;
    final row = DirectionExecutionRow(
      kind: kind,
      date: date,
      material: material,
      client: directionExecutionClient(client),
      shift: shift,
    );
    rows[row.key] = row;
  }

  if (kind == 'production') {
    planned.addAll(plannedProduction);
    for (var d = 0; d < 5; d++) {
      for (final s in ['DAY', 'NIGHT']) {
        for (final m in _suggestionMaterials) {
          seed(week.add(Duration(days: d)), m, '', s);
        }
      }
    }
    for (final p in production) {
      final key = directionExecutionKey(
        kind,
        p.date,
        p.materialCode,
        '',
        p.shiftKey,
      );
      if (rows.containsKey(key))
        operations[key] = (operations[key] ?? 0) + p.quantity;
    }
  } else {
    for (final s in shipments.where((s) => !s.isCancelled)) {
      seed(s.shipDate, s.materialCode, s.clientName);
      final key = directionExecutionKey(
        kind,
        s.shipDate,
        s.materialCode,
        s.clientName,
      );
      planned[key] = (planned[key] ?? 0) + s.plannedQuantity;
    }
    for (final s in directionShipmentSourcePlans(
      shipments,
      confirmations,
    ).where((s) => s.isShipped)) {
      seed(s.shipDate, s.materialCode, s.clientName);
      final key = directionExecutionKey(
        kind,
        s.shipDate,
        s.materialCode,
        s.clientName,
      );
      legacy[key] = (legacy[key] ?? 0) + s.plannedQuantity;
      legacyLoads.putIfAbsent(key, () => []).add(s.plannedQuantity);
    }
    for (final m in movements.where(
      (m) => m.flow == 'OUT' && m.origin != 'TRANSFORMATION',
    )) {
      if (directionShipmentMaterialByCode(m.material) == null) continue;
      final option = directionShipmentMaterialByCode(m.material)!;
      if ((option.isPacked && m.level != 'COMMERCIAL') ||
          (option.isBulk && m.level != 'GENERAL'))
        continue;
      final amount = option.isPacked ? m.bales : m.kilograms.round();
      if (amount <= 0) continue;
      seed(m.date, m.material, m.client);
      final key = directionExecutionKey(kind, m.date, m.material, m.client);
      operations[key] = (operations[key] ?? 0) + amount;
      operationLoads.putIfAbsent(key, () => []).add(amount);
    }
  }
  for (final a in saved.values) {
    seed(a.date, a.material, a.client, a.shift);
  }
  return [
    for (final row in rows.values)
      DirectionExecutionRow(
        kind: kind,
        date: row.date,
        material: row.material,
        client: row.client,
        shift: row.shift,
        planned: planned[row.key],
        observed: (legacy[row.key] ?? -1) > (operations[row.key] ?? -1)
            ? legacy[row.key]
            : operations[row.key],
        observedLoads: (legacy[row.key] ?? -1) > (operations[row.key] ?? -1)
            ? legacyLoads[row.key] ?? []
            : operationLoads[row.key] ?? [],
        confirmation: saved[row.key],
      ),
  ]..sort((a, b) {
    final date = b.date.compareTo(a.date);
    if (date != 0) return date;
    return '${a.client}|${a.material}|${a.shift}'.compareTo(
      '${b.client}|${b.material}|${b.shift}',
    );
  });
}
